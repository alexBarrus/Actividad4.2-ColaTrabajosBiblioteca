    private void btnEncolarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEncolarActionPerformed
        try {
            Trabajo trabajo = crearTrabajoDesdeFormulario();   // referencia polimórfica
            cola.offer(trabajo);
            txtResultado.setText("ENCOLADO al final de la cola (" + trabajo.getTipo() + "):\n" + trabajo);
            limpiarCampos();
            actualizarVista();
        } catch (IllegalArgumentException e) {
            advertencia("Datos inválidos", e.getMessage());
        }
    }//GEN-LAST:event_btnEncolarActionPerformed

    private void btnAtenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtenderActionPerformed
        if (cola.isEmpty()) {
            advertencia("Cola vacía", "No se puede atender (poll): la cola está vacía.");
            return;
        }
        Trabajo atendido = cola.poll();
        atendidos++;
        txtResultado.setText("ATENDIDO (poll) #" + atendidos + " - salió del frente:\n" + atendido
                + "\n\nTipo: " + atendido.getTipo()
                + "\nQuedan " + cola.size() + " trabajo(s) en la cola.");
        actualizarVista();
    }//GEN-LAST:event_btnAtenderActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        if (cola.isEmpty()) {
            advertencia("Cola vacía", "No se puede consultar el frente (peek): la cola está vacía.");
            return;
        }
        Trabajo frente = cola.peek();
        txtResultado.setText("FRENTE de la cola (peek, no se remueve):\n" + frente
                + "\n\nLa cola sigue teniendo " + cola.size() + " trabajo(s).");
        actualizarVista();
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnVaciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVaciarActionPerformed
        if (cola.isEmpty()) {
            advertencia("Cola vacía", "La cola ya se encuentra vacía.");
            return;
        }
        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Desea eliminar los " + cola.size() + " trabajo(s) de la cola?",
                "Vaciar cola", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }
        int eliminados = cola.size();
        cola.vaciarCola();
        actualizarVista();
        txtResultado.setText("Cola vaciada: se eliminaron " + eliminados + " trabajo(s).\nisEmpty() = " + cola.isEmpty());
        JOptionPane.showMessageDialog(this, "La cola fue vaciada correctamente.\nisEmpty() = " + cola.isEmpty(),
                "Vaciar cola", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnVaciarActionPerformed

