    /**
     * Habilita solo el campo específico de la subclase seleccionada
     * y limpia los que no aplican.
     */
    private void actualizarCampos() {
        String tipo = (String) cmbTipo.getSelectedItem();
        habilitar(lblPaginas, txtPaginas, "Libro".equals(tipo));
        habilitar(lblEdicion, txtEdicion, "Revista".equals(tipo));
        habilitar(lblConferencia, txtConferencia, "Articulo".equals(tipo));
    }

    private void habilitar(javax.swing.JLabel etiqueta, JTextField campo, boolean activo) {
        etiqueta.setEnabled(activo);
        campo.setEnabled(activo);
        if (!activo) {
            campo.setText("");
        }
    }

    /**
     * Lee el formulario, valida y crea la subclase que corresponda.
     * Devuelve el objeto como Trabajo (polimorfismo).
     *
     * @throws IllegalArgumentException con un mensaje claro si algún dato es inválido
     */
    private Trabajo crearTrabajoDesdeFormulario() {
        String titulo = leerTexto(txtTitulo, "Título");
        String autor = leerTexto(txtAutor, "Autor");
        int anio = leerEnteroPositivo(txtAnio, "Año de publicación");

        String tipo = (String) cmbTipo.getSelectedItem();
        switch (tipo) {
            case "Libro":
                return new Libro(titulo, autor, anio, leerEnteroPositivo(txtPaginas, "Número de páginas"));
            case "Revista":
                return new Revista(titulo, autor, anio, leerEnteroPositivo(txtEdicion, "Número de edición"));
            case "Articulo":
                return new Articulo(titulo, autor, anio, leerTexto(txtConferencia, "Nombre de la conferencia"));
            default:
                throw new IllegalArgumentException("Tipo de publicación desconocido: " + tipo);
        }
    }

    private String leerTexto(JTextField campo, String nombre) {
        String valor = campo.getText().trim();
        if (valor.isEmpty()) {
            campo.requestFocus();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" no puede estar vacío.");
        }
        return valor;
    }

    private int leerEnteroPositivo(JTextField campo, String nombre) {
        String texto = campo.getText().trim();
        if (texto.isEmpty()) {
            campo.requestFocus();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" no puede estar vacío.");
        }
        int valor;
        try {
            valor = Integer.parseInt(texto);
        } catch (NumberFormatException e) {
            campo.requestFocus();
            campo.selectAll();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" debe ser un número entero (escribió: \"" + texto + "\").");
        }
        if (valor <= 0) {
            campo.requestFocus();
            campo.selectAll();
            throw new IllegalArgumentException("El campo \"" + nombre + "\" debe ser un entero mayor a cero.");
        }
        return valor;
    }

    private void limpiarCampos() {
        txtTitulo.setText("");
        txtAutor.setText("");
        txtAnio.setText("");
        txtPaginas.setText("");
        txtEdicion.setText("");
        txtConferencia.setText("");
        txtTitulo.requestFocus();
    }

    private void advertencia(String titulo, String mensaje) {
        txtResultado.setText("ADVERTENCIA: " + mensaje);
        JOptionPane.showMessageDialog(this, mensaje, titulo, JOptionPane.WARNING_MESSAGE);
    }

    /**
     * Redibuja la cola completa, del FRENTE (sale primero) al FINAL (entra aquí).
     */
    private void actualizarVista() {
        StringBuilder sb = new StringBuilder();
        List<Trabajo> elementos = cola.listar();
        if (elementos.isEmpty()) {
            sb.append("\n   (La cola está vacía)\n\n");
            sb.append("   Use \"Encolar (Offer)\" para agregar trabajos.");
        } else {
            sb.append("               Sale por aquí (poll / peek)\n");
            sb.append("                ▲\n");
            for (int i = 0; i < elementos.size(); i++) {
                String marca;
                if (elementos.size() == 1) {
                    marca = "FRENTE/FINAL";
                } else if (i == 0) {
                    marca = "FRENTE";
                } else if (i == elementos.size() - 1) {
                    marca = "FINAL";
                } else {
                    marca = "";
                }
                sb.append(String.format(" %-13s %2d. %s%n", marca, i + 1, elementos.get(i)));
            }
            sb.append("                ▲\n");
            sb.append("               Entra por aquí (offer)\n");
        }
        txtCola.setText(sb.toString());
        txtCola.setCaretPosition(0);
        lblEstado.setText("Elementos en la cola: " + cola.size() + "   |   isEmpty(): " + cola.isEmpty()
                + "   |   Atendidos: " + atendidos);
    }

